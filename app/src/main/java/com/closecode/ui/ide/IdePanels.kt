/** Spec 7 logcat levels. Verbose is muted, Debug accent, Info green, Warn amber, Error red. */
enum class LogLevel(val label: String, val letter: Char) {
    VERBOSE("Verbose", 'V'),
    DEBUG("Debug", 'D'),
    INFO("Info", 'I'),
    WARN("Warn", 'W'),
    ERROR("Error", 'E'),
}

/** One logcat row. [formatted] matches the spec's `HH:mm:ss.SSS L/Tag: message`. */
data class LogLine(
    val level: LogLevel,
    val tag: String,
    val message: String,
    val time: String = NOW.format(LocalTime.now()),
) {
    val formatted: String get() = "$time ${level.letter}/$tag: $message"
    val sortableLevel: Int get() = level.ordinal

    companion object {
        private val NOW: DateTimeFormatter = DateTimeFormatter.ofPattern("HH:mm:ss.SSS")
    }
}

/** Spec 7: the log is capped at 1,000 lines. */
const val LOGCAT_MAX_LINES = 1_000

/**
 * Appends while enforcing the cap. Dropping the oldest lines is one array copy of at most a
 * thousand elements, which is cheap enough per line and keeps the bound strict: the list never
 * holds more than [LOGCAT_MAX_LINES], rather than drifting up to a batch threshold.
 */
fun MutableList<LogLine>.appendCapped(line: LogLine) {
    add(line)
    if (size > LOGCAT_MAX_LINES) {
        // Excess is usually 1, so this clears a short prefix and shifts the rest once.
        subList(0, size - LOGCAT_MAX_LINES).clear()
    }
}

/** Spec 7 build task names, in execution order. */
val BuildTasks = listOf(
    "preBuild",
    "compileDebugKotlin",
    "mergeDebugResources",
    "dexBuilderDebug",
    "packageDebug",
    "assembleDebug",
)

/**
 * The way out of Logcat and Build. Neither panel has a path bar, so without this the bottom
 * navigation was the only escape from a screen the top bar's build button had just opened.
 */
@Composable
private fun PanelBackBar(title: String, onBack: () -> Unit) {
    val c = LocalPageColors.current
    Row(
        Modifier
            .fillMaxWidth()
            .padding(horizontal = 12.dp, vertical = 8.dp),
        horizontalArrangement = Arrangement.spacedBy(8.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Box(
            Modifier
                .clip(RoundedCornerShape(9.dp))
                .background(c.panel2)
                .border(1.dp, c.ln, RoundedCornerShape(9.dp))
                .clickable(onClick = onBack)
                .padding(horizontal = 10.dp, vertical = 6.dp),
        ) {
            Text(
                text = "‹ Code",
                color = c.ac,
                fontSize = 12.sp,
                fontFamily = Sans,
                fontWeight = FontWeight.SemiBold,
            )
        }
        Text(
            text = title,
            color = c.tx,
            fontSize = 13.sp,
            fontFamily = Sans,
            fontWeight = FontWeight.SemiBold,
        )
    }
}

/**
 * Spec 7 Logcat panel: filter chips, one mono row per line with a divider, long lines wrapping.
 *
 * The log is generated by the app's own analysis and build events. There is no real device
 * logcat on Android, so the header says so rather than implying otherwise.
 */
@Composable
fun IdeLogcatPanel(
    lines: List<LogLine>,
    modifier: Modifier = Modifier,
    filter: LogLevel? = null,
    onFilterChange: (LogLevel?) -> Unit = {},
    onBack: () -> Unit = {},
) {
    val c = LocalPageColors.current
    val visible = remember(lines, filter) {
        if (filter == null) lines else lines.filter { it.level == filter }
    }

    Column(modifier.fillMaxSize().background(c.bg)) {
        PanelBackBar("Logcat", onBack)
        Row(
            Modifier
                .fillMaxWidth()
                .padding(horizontal = 12.dp, vertical = 8.dp),
            horizontalArrangement = Arrangement.spacedBy(6.dp),
            verticalAlignment = Alignment.CenterVertically,
        ) {
            FilterChip("All", filter == null) { onFilterChange(null) }
            for (level in LogLevel.entries) {
                FilterChip(level.label, filter == level) { onFilterChange(level) }
            }
        }
        SimulatedBanner("Simulated log — this app has no access to the device logcat.")

        Box(Modifier.weight(1f).verticalScroll(rememberScrollState())) {
            if (visible.isEmpty()) {
                Text(
                    text = "Run the app to see logs.",
                    color = c.mu,
                    fontSize = 13.sp,
                    fontFamily = Mono,
                    modifier = Modifier.padding(40.dp),
                )
                return@Column
            }
            Column(Modifier.fillMaxWidth()) {
                visible.forEach { line ->
                    Row(
                        Modifier
                            .fillMaxWidth()
                            .padding(vertical = 2.dp),
                    ) {
                        Text(
                            text = line.formatted,
                            color = when (line.level) {
                                LogLevel.INFO -> c.success
                                LogLevel.WARN -> c.amber
                                LogLevel.ERROR -> c.red
                                LogLevel.DEBUG -> c.ac
                                LogLevel.VERBOSE -> c.mu
                            },
                            fontSize = 13.sp,
                            fontFamily = Mono,
                            modifier = Modifier.weight(1f),
                        )
                    }
                    Box(Modifier.fillMaxWidth().height(1.dp).background(c.ln.copy(alpha = 0.45f)))
                }
            }
        }
    }
}

/**
 * Spec 7 Build panel: a 6 dp progress bar, one row per Gradle task with a status glyph, and a
 * bold result line. Simulated — there is no Gradle daemon in the app — and blocked while the
 * project has compile errors.
 */
@Composable
fun IdeBuildPanel(
    building: Boolean,
    errorCount: Int,
    onRun: () -> Unit,
    modifier: Modifier = Modifier,
    completedTasks: Int = if (building) 0 else BuildTasks.size,
    onBack: () -> Unit = {},
) {
    val c = LocalPageColors.current
    val failed = errorCount > 0
    val progress = if (building) {
        completedTasks.toFloat() / BuildTasks.size.coerceAtLeast(1)
    } else if (failed) {
        1f / BuildTasks.size
    } else {
        1f
    }

    Column(modifier.fillMaxSize().background(c.bg)) {
        PanelBackBar("Build", onBack)
        Row(
            Modifier
                .fillMaxWidth()
                .padding(horizontal = 12.dp, vertical = 10.dp),
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(10.dp),
        ) {
            Box(
                Modifier
                    .weight(1f)
                    .height(6.dp)
                    .clip(RoundedCornerShape(4.dp))
                    .background(c.panel2),
            ) {
                Box(
                    Modifier
                        .fillMaxWidth(progress.coerceIn(0f, 1f))
                        .height(6.dp)
                        .clip(RoundedCornerShape(4.dp))
                        .background(c.ac),
                )
            }
            Box(
                Modifier
                    .clip(RoundedCornerShape(9.dp))
                    .background(if (failed) c.red else c.ac)
                    .clickable(onClick = onRun)
                    .padding(horizontal = 12.dp, vertical = 7.dp),
            ) {
                Text(
                    text = if (building) "Building" else "Run Build",
                    color = c.af,
                    fontSize = 12.sp,
                    fontFamily = Sans,
                    fontWeight = FontWeight.SemiBold,
                )
            }
        }
        SimulatedBanner("Simulated build — the app does not run Gradle.")

        Column(Modifier.weight(1f).verticalScroll(rememberScrollState())) {
            BuildTasks.forEachIndexed { index, task ->
                val state = when {
                    failed && index == 1 -> TaskState.FAILED
                    building && index < completedTasks -> TaskState.DONE
                    building && index == completedTasks -> TaskState.RUNNING
                    !building && !failed -> TaskState.DONE
                    else -> TaskState.PENDING
                }
                Row(
                    Modifier
                        .fillMaxWidth()
                        .padding(vertical = 8.dp, horizontal = 12.dp),
                    verticalAlignment = Alignment.CenterVertically,
                ) {
                    Text(
                        text = when (state) {
                            TaskState.PENDING -> "."
                            TaskState.RUNNING -> "..."
                            TaskState.DONE -> "✓"
                            TaskState.FAILED -> "✗"
                        },
                        color = when (state) {
                            TaskState.DONE -> c.success
                            TaskState.FAILED -> c.red
                            else -> c.mu
                        },
                        fontSize = 13.sp,
                        fontFamily = Mono,
                        fontWeight = FontWeight.Bold,
                        modifier = Modifier.size(width = 18.dp, height = 18.dp),
                    )
                    Text(
                        text = ":app:$task",
                        color = c.tx,
                        fontSize = 13.sp,
                        fontFamily = Mono,
                    )
                }
                Box(Modifier.fillMaxWidth().height(1.dp).background(c.ln.copy(alpha = 0.45f)))
            }
            Text(
                text = if (failed) {
                    "BUILD FAILED · $errorCount compile errors. Open the marked lines to fix."
                } else {
                    "BUILD SUCCESSFUL"
                },
                color = if (failed) c.red else c.success,
                fontSize = 13.sp,
                fontFamily = Sans,
                fontWeight = FontWeight.Bold,
                modifier = Modifier.padding(12.dp),
            )
        }
    }
}

private enum class TaskState { PENDING, RUNNING, DONE, FAILED }

/** The persistent "simulated" label the spec requires on Build and Logcat. */
@Composable
private fun SimulatedBanner(text: String) {
    val c = LocalPageColors.current
    Row(
        Modifier
            .fillMaxWidth()
            .padding(horizontal = 12.dp, vertical = 4.dp),
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.spacedBy(6.dp),
    ) {
        Box(
            Modifier
                .clip(RoundedCornerShape(6.dp))
                .background(c.warnPillBg)
                .padding(horizontal = 6.dp, vertical = 2.dp),
        ) {
            Text(
                text = "SIMULATED",
                color = c.warnPillTx,
                fontSize = 11.sp,
                fontFamily = Sans,
                fontWeight = FontWeight.Bold,
            )
        }
        Text(
            text = text,
            color = c.mu,
            fontSize = 11.sp,
            fontFamily = Sans,
        )
    }
}

@Composable
private fun FilterChip(label: String, active: Boolean, onClick: () -> Unit) {
    val c = LocalPageColors.current
    Box(
        Modifier
            .clip(RoundedCornerShape(99.dp))
            .background(if (active) c.ac else Color.Transparent)
            .border(1.dp, if (active) c.ac else c.ln, RoundedCornerShape(99.dp))
            .clickable(onClick = onClick)
            .padding(horizontal = 11.dp, vertical = 3.dp),
    ) {
        Text(
            text = label,
            color = if (active) Color.White else c.tx,
            fontSize = 12.sp,
            fontFamily = Sans,
            fontWeight = FontWeight.SemiBold,
            maxLines = 1,
        )
    }
}